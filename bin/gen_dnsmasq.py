#!/usr/bin/env python3
"""Generate configs/dnsmasq.conf (our private DNS server) from live facts + peers.json.

  gen_dnsmasq.py                  edge IP = mac_aanya's IP from peers.json (from her own info.json)
  gen_dnsmasq.py --app-ip X       failure demo F2: point app.subspace-67.test at X instead
  gen_dnsmasq.py --out FILE       write somewhere else (default configs/dnsmasq.conf)

Prints CHANGED or UNCHANGED (exit 0), or an error (exit 1). Validates with `dnsmasq --test`.
Then installs a byte-identical copy as Homebrew's /opt/homebrew/etc/dnsmasq.conf, which the root
dnsmasq service loads. (A copy, not a conf-file= include: macOS privacy protection (TCC) stops a
root launchd daemon from reading or writing anything under ~/Desktop; the first attempt with an
include + a log file in the project folder crash-looped with dnsmasq exit code 3 = filesystem
problem. For the same reason the query log lives in /opt/homebrew/var/log, symlinked from logs/.)
"""
import argparse, json, os, re, subprocess, sys

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BREW_CONF = "/opt/homebrew/etc/dnsmasq.conf"
QUERY_LOG = "/opt/homebrew/var/log/dnsmasq_subspace_67.log"
DNSMASQ = "/opt/homebrew/opt/dnsmasq/sbin/dnsmasq"
ZONE = "subspace-67.test"


def sh(*cmd, timeout=10):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout).stdout
    except Exception:
        return ""


def answers_dns(server):
    out = sh("dig", f"@{server}", "example.com", "A", "+short", "+time=1", "+tries=1", timeout=5)
    return bool(re.search(r"^\d+\.\d+\.\d+\.\d+$", out, re.M))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--app-ip")
    ap.add_argument("--out", default=os.path.join(PROJECT_DIR, "configs", "dnsmasq.conf"))
    a = ap.parse_args()

    iface = (re.search(r"interface:\s*(\S+)", sh("route", "-n", "get", "default")) or [None, "en0"])[1]
    my_ip = sh("ipconfig", "getifaddr", iface).strip()
    gw = (re.search(r"gateway:\s*(\S+)", sh("route", "-n", "get", "default")) or [None, ""])[1]
    try:
        peers = json.load(open(os.path.join(PROJECT_DIR, "peers.json")))
        edge_ip = peers["mac_aanya"]["ip"]
    except Exception:
        sys.exit("ERROR: mac_aanya not in peers.json yet (run bin/discover.py)")
    if not my_ip:
        sys.exit("ERROR: no LAN IP on " + iface)
    app_ip = a.app_ip or edge_ip

    # Upstream resolvers for non-local names. The spec asks for the gateway + 1.1.1.1; if the gateway
    # does not run a resolver (true on the campus Wi-Fi: dig @gateway times out) we use the resolvers
    # DHCP hands out instead, keeping only those that really answer.
    dhcp = re.findall(r"\d+\.\d+\.\d+\.\d+",
                      (re.search(r"domain_name_server \(ip_mult\): \{([^}]*)\}", sh("ipconfig", "getpacket", iface)) or [None, ""])[1])
    upstream, notes = [], []
    if gw and answers_dns(gw):
        upstream.append(gw)
    elif gw:
        notes.append(f"# gateway {gw} does not answer DNS here (dig @{gw} times out), so it is not used;")
        notes.append(f"# the DHCP-provided resolvers that do answer are used in its place.")
    for s in dhcp:
        if s not in upstream and s != my_ip and not s.startswith("127.") and answers_dns(s):
            upstream.append(s)
    if "1.1.1.1" not in upstream:
        upstream.append("1.1.1.1")

    lines = [
        "# subspace_67 private DNS server (dnsmasq) on mac_vachan",
        "# Generated by bin/gen_dnsmasq.py from live network facts + peers.json (mac_aanya's own info.json).",
        "# Do not hand-edit: start.sh regenerates it when an IP changes. The root Homebrew service loads a",
        f"# byte-identical copy at {BREW_CONF} (a root launchd daemon may not read ~/Desktop on macOS).",
        f"# this DNS server (mac_vachan) = {my_ip}; edge (mac_aanya) = {edge_ip}; gateway = {gw}",
        "",
        "# ---- our private zone: answered here with authority, never forwarded upstream ----",
        f"local=/{ZONE}/",
        f"host-record=app.{ZONE},{app_ip}",
        f"host-record=api.{ZONE},{edge_ip}",
        "# TTL (seconds) clients may cache our answers",
        "local-ttl=60",
        "",
        "# ---- every other name is forwarded to real resolvers ----",
        "# no-resolv: ignore /etc/resolv.conf. Once this Mac uses itself as DNS, resolv.conf points back",
        "# at us, so reading it would create a forwarding loop.",
        "no-resolv",
        *notes,
        *[f"server={s}" for s in upstream],
        "# never forward single-label names or reverse lookups of private ranges to the internet",
        "domain-needed",
        "bogus-priv",
        "no-hosts",
        "cache-size=1000",
        "",
        "# ---- where we listen: this Mac's LAN IP (for the other Macs) + loopback (for itself) ----",
        "# macOS dnsmasq always binds each address separately (it forces bind-interfaces), and binding",
        "# port 53 on a specific address needs root: the service is started by root, then drops to nobody.",
        f"listen-address={my_ip}",
        "listen-address=127.0.0.1",
        "bind-interfaces",
        "user=nobody",
        "# group staff: the log file dnsmasq creates stays readable by the project owner",
        "group=staff",
        "",
        "# ---- logging: one line per query including the asking client's IP (proves who asked) ----",
        "# (outside ~/Desktop for the root daemon; PROJECT_DIR/logs/dnsmasq.log is a symlink to it)",
        "log-queries=extra",
        f"log-facility={QUERY_LOG}",
        "log-async=25",
        "",
    ]
    new = "\n".join(lines)
    old = open(a.out).read() if os.path.exists(a.out) else None
    if old != new:
        tmp = a.out + ".tmp"
        open(tmp, "w").write(new)
        test = subprocess.run([DNSMASQ, "--test", "-C", tmp], capture_output=True, text=True)
        if test.returncode != 0:
            sys.exit(f"ERROR: dnsmasq --test rejected the new config: {test.stderr.strip()}")
        os.replace(tmp, a.out)
    installed_changed = False
    if a.out == os.path.join(PROJECT_DIR, "configs", "dnsmasq.conf"):
        cur = open(BREW_CONF).read() if os.path.exists(BREW_CONF) else ""
        if cur != new:
            tmp = BREW_CONF + ".tmp"
            open(tmp, "w").write(new)
            os.replace(tmp, BREW_CONF)
            installed_changed = True
        link = os.path.join(PROJECT_DIR, "logs", "dnsmasq.log")
        if not os.path.exists(QUERY_LOG):
            open(QUERY_LOG, "a").close()
            os.chmod(QUERY_LOG, 0o644)          # stays readable after dnsmasq chowns it to nobody
        if os.path.realpath(link) != QUERY_LOG:
            if os.path.lexists(link):
                os.remove(link)
            os.symlink(QUERY_LOG, link)
    changed = old != new or installed_changed
    print(("CHANGED" if changed else "UNCHANGED") + f" {a.out} (app->{app_ip}, api->{edge_ip}, listen {my_ip}, upstream {','.join(upstream)})"
          + (f"; installed copy {BREW_CONF} updated" if installed_changed else ""))


if __name__ == "__main__":
    main()
