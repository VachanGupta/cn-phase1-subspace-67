#!/usr/bin/env python3
"""Generate the edge's nginx config from peers.json (never hard-coded IPs).

Usage:  python3 scripts/gen_nginx_conf.py [--port 443|8443]
Writes:
  configs/nginx_subspace_67.conf           the edge config (upstream, TLS, redirects, logging)
  /opt/homebrew/etc/nginx/nginx.conf       Homebrew's main config, reduced to "include" our file
                                           (the original is kept once as nginx.conf.orig_subspace67)
The edge port is remembered in run/edge_port. Prints "changed" or "unchanged" so start.sh
knows whether nginx needs a reload.
"""
import datetime
import json
import os
import shutil
import sys

P = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PEERS = os.path.join(P, "peers.json")
SITE = os.path.join(P, "configs", "nginx_subspace_67.conf")
BREW_ETC = "/opt/homebrew/etc/nginx"
MAIN = os.path.join(BREW_ETC, "nginx.conf")
MAIN_ORIG = MAIN + ".orig_subspace67"
PORT_FILE = os.path.join(P, "run", "edge_port")

MESSAGE = ("subspace_67 edge: please use the domain name, e.g. https://app.subspace-67.test/ "
           "(requests by IP address or for unknown host names are not served)\\n")


def load_peers():
    try:
        with open(PEERS) as f:
            return json.load(f)
    except Exception:
        return {}


def site_conf(abhay_ip, vachan_ip, port):
    https_url = "https://$host" + ("" if port == 443 else f":{port}") + "$request_uri"
    ups = []
    if abhay_ip:
        ups.append(f"    server {abhay_ip}:3001 max_fails=1 fail_timeout=10s;   # Backend A @ mac_abhay")
    else:
        ups.append("    # Backend A @ mac_abhay: not discovered yet")
    if vachan_ip:
        ups.append(f"    server {vachan_ip}:3002 max_fails=1 fail_timeout=10s;   # Backend B @ mac_vachan")
    else:
        ups.append("    # Backend B @ mac_vachan: not discovered yet")
    if not (abhay_ip or vachan_ip):
        ups.append("    server 127.0.0.1:9 down;   # placeholder so nginx -t passes before discovery")
    upstream = "\n".join(ups)
    now = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    return f"""# =====================================================================================
# subspace_67 edge on mac_aanya: TLS termination + round-robin load balancer
# GENERATED by scripts/gen_nginx_conf.py ({now}). Don't edit by hand; run start.sh.
# Backend IPs come from each peer's own info.json (peers.json), never hard-coded.
# Included from Homebrew's /opt/homebrew/etc/nginx/nginx.conf, inside the http {{}} block.
# =====================================================================================

server_tokens off;   # don't advertise the nginx version in headers / error pages
gzip          off;   # never re-encode proxied bodies: Content-Length and ETag stay exactly the backend's
# (and deliberately NO proxy_cache: every request must reach a backend so X-Backend alternates,
#  and Cache-Control / ETag / Last-Modified / 304 pass through untouched)

# Edge-side proof of load balancing and failover: who asked, which backend answered, over which TLS.
log_format subspace67 '$time_iso8601 client=$remote_addr:$remote_port host=$host "$request" '
                      'status=$status bytes=$body_bytes_sent proto=$server_protocol tls=$ssl_protocol '
                      'upstream=$upstream_addr upstream_status=$upstream_status x_backend=$upstream_http_x_backend '
                      'request_time=$request_time upstream_connect=$upstream_connect_time upstream_header=$upstream_header_time upstream_time=$upstream_response_time';
access_log {P}/logs/nginx_access.log subspace67;

# TLS settings shared by every HTTPS server block below
ssl_certificate     {P}/tls/fullchain.crt;   # leaf + CA (the chain the client sees)
ssl_certificate_key {P}/tls/server.key;      # private key, chmod 600, never shared
ssl_protocols       TLSv1.2 TLSv1.3;         # 1.2 kept so a capture can show the Certificate message in clear
ssl_session_cache   shared:SSL:1m;
ssl_session_timeout 10m;

# The pool. No balancing directive = round robin (A, B, A, B, ...).
# max_fails=1 fail_timeout=10s: one failed attempt takes a backend out of rotation for 10 s.
# zone: nginx runs one worker per CPU core; without a shared-memory zone each worker keeps
# its own round-robin pointer and failure counters (so the order looks random and a dead
# backend is "discovered" once per worker). With the zone all workers share one state.
upstream team_backends {{
    zone team_backends 1m;
{upstream}
}}

# ---- HTTPS: the real service -------------------------------------------------------
server {{
    listen {port} ssl;
    http2  on;
    server_name app.subspace-67.test api.subspace-67.test;

    location / {{
        proxy_pass http://team_backends;               # plain HTTP to the backends on the LAN
        proxy_http_version 1.1;
        proxy_next_upstream error timeout http_502 http_503;   # failover: retry the other backend
        proxy_connect_timeout 2s;                      # a dead backend is detected within 2 s
        proxy_read_timeout 10s;
        proxy_set_header Host              $host;                       # original name the client asked for
        proxy_set_header X-Real-IP         $remote_addr;                # real client IP
        proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;  # client IP chain
        proxy_set_header X-Forwarded-Proto $scheme;                     # "https": TLS ended at the edge
    }}
}}

# ---- HTTPS default: bare IP / unknown SNI or Host -> tell the user to use the name ------
server {{
    listen {port} ssl default_server;
    http2  on;
    server_name _;
    default_type text/plain;
    return 400 "{MESSAGE}";
}}

# ---- HTTP :80 -> HTTPS -------------------------------------------------------------
server {{
    listen 80;
    server_name app.subspace-67.test api.subspace-67.test;
    return 301 {https_url};
}}

# ---- HTTP :80 default: bare IP / unknown Host ----------------------------------------
server {{
    listen 80 default_server;
    server_name _;
    default_type text/plain;
    return 400 "{MESSAGE}";
}}
"""


def main_conf():
    return f"""# Homebrew nginx main config, reduced for subspace_67 by scripts/gen_nginx_conf.py.
# The original is saved next to it as nginx.conf.orig_subspace67 (restore_network.sh puts it back).
worker_processes  auto;
error_log  {P}/logs/nginx_error.log  notice;
pid        {P}/run/nginx.pid;

events {{
    worker_connections  1024;
}}

http {{
    include       mime.types;
    default_type  application/octet-stream;
    sendfile      on;
    keepalive_timeout  65;

    include {P}/configs/nginx_subspace_67.conf;
}}
"""


def write_if_changed(path, text):
    try:
        with open(path) as f:
            if f.read() == text:
                return False
    except FileNotFoundError:
        pass
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)
    return True


def strip_stamp(text):
    return "\n".join(l for l in text.splitlines() if "GENERATED by" not in l)


def main():
    port = None
    if "--port" in sys.argv:
        port = int(sys.argv[sys.argv.index("--port") + 1])
    if port is None:
        try:
            port = int(open(PORT_FILE).read().strip())
        except Exception:
            port = 443
    os.makedirs(os.path.dirname(PORT_FILE), exist_ok=True)
    with open(PORT_FILE, "w") as f:
        f.write(f"{port}\n")

    peers = load_peers()
    abhay = peers.get("mac_abhay", {}).get("ip")
    vachan = peers.get("mac_vachan", {}).get("ip")

    new_site = site_conf(abhay, vachan, port)
    try:
        old_site = open(SITE).read()
    except FileNotFoundError:
        old_site = ""
    changed = strip_stamp(old_site) != strip_stamp(new_site)
    if changed:
        write_if_changed(SITE, new_site)

    if os.path.exists(MAIN) and not os.path.exists(MAIN_ORIG):
        shutil.copy2(MAIN, MAIN_ORIG)
    changed |= write_if_changed(MAIN, main_conf())

    print(("changed" if changed else "unchanged") + f" port={port} A={abhay} B={vachan}")


if __name__ == "__main__":
    main()
